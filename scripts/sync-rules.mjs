// Regenerates shared/summaryRules.ts from the supplied rules file so serverless
// functions can use the rubric without runtime file-system access.
import { readFileSync, writeFileSync } from 'node:fs';

const rules = readFileSync(new URL('../exercise_data/summary-rules.txt', import.meta.url), 'utf8');
const out = `// AUTO-GENERATED by scripts/sync-rules.mjs from exercise_data/summary-rules.txt. Do not edit by hand.\nexport const SUMMARY_RULES = ${JSON.stringify(rules)};\n`;
writeFileSync(new URL('../shared/summaryRules.ts', import.meta.url), out);
console.log('shared/summaryRules.ts updated');
